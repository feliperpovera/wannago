function wgApply(lang) {
  wgLang = lang;
  document.documentElement.lang = lang;
  const tr = (orig) => lang === 'en' ? (WG_EN[orig] || orig) : orig;

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode: n => /SCRIPT|STYLE/.test(n.parentNode.nodeName) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT
  });
  for (let n; (n = walker.nextNode());) {
    if (n.wgOrig === undefined) {
      const key = n.nodeValue.replace(/\s+/g, ' ').trim();
      if (!WG_EN[key]) continue;
      n.wgOrig = key; n.wgPre = n.nodeValue.match(/^\s*/)[0]; n.wgPost = n.nodeValue.match(/\s*$/)[0];
    }
    n.nodeValue = n.wgPre + tr(n.wgOrig) + n.wgPost;
  }
  document.querySelectorAll('*').forEach(el => WG_ATTRS.forEach(a => {
    if (!el.hasAttribute(a)) return;
    const key = 'wgOrig_' + a;
    if (el[key] === undefined) { if (!WG_EN[el.getAttribute(a)]) return; el[key] = el.getAttribute(a); }
    el.setAttribute(a, tr(el[key]));
  }));
  if (document.wgTitle === undefined) document.wgTitle = document.title;
  document.title = tr(document.wgTitle);

  document.querySelectorAll('.lang-btn').forEach(b => {
    b.textContent = lang === 'en' ? 'ES' : 'EN';
    b.setAttribute('aria-label', lang === 'en' ? 'Cambiar a español' : 'Switch to English');
  });
  try { localStorage.setItem('wg-lang', lang); } catch (e) {}
  dispatchEvent(new CustomEvent('wg-lang', { detail: lang }));
}

